#include <stdio.h>
#include <math.h>
#include <windows.h>

int main() {
    SetConsoleOutputCP(CP_UTF8);
    int n;
    double x;

    printf("Введите n: ");
    scanf("%d", &n);
    if (n < 1) {
        printf("Число n должно быть положительным.\n");
        return 1;
    }
    printf("Введите x: ");
    scanf("%lf", &x);

    double pi = acos(-1.0);
    double head = sqrt(pi / 2 + fabs(x));
    double product = 1;
    for (int k = 1; k <= n; k++) {
        product *= exp(cbrt(k - x)) / (k * k + x) + 1.1;
    }

    double result = head - product;

    if (isfinite(result)) {
        printf("\nРезультат: %lf\n", result);
    } else {
        printf("\nРезультат: не определён\n");
    }

    return 0;
}
